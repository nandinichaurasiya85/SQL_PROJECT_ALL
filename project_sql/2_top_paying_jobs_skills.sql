/*Question : What skills are required for the top paying data analyst jobs ?
-use the top 10 highest paying data analyst jobs from first query 
-add the specific skills reqiured for these roles 
-why ?It provides a detailed look at which high -paying jobs demand certain skills,
 helping job seekers understand which skills to develop that align with top salaries */


select 
       job_postings_fact.job_id,
       job_postings_fact.job_title,
       salary_year_avg,
       name as company_name,skills
from 
       job_postings_fact
LEFT JOIN
       company_dim ON job_postings_fact.company_id = company_dim.company_id
LEFT JOIN
       skills_job_dim ON job_postings_fact.job_id = skills_job_dim.job_id
LEFT JOIN
       skills_dim ON skills_job_dim.skill_id = skills_dim.skill_id
      
where 
     job_title_short = 'Data Analyst' and job_location = 'Anywhere'
    and salary_year_avg is not null and skills_dim.skills is not null
order by
      salary_year_avg desc
limit 10

with top_paying_jobs as(
      select job_postings_fact.job_id,
       job_postings_fact.job_title,
       job_postings_fact.salary_year_avg,
       company_dim.name as company_name
    from 
       job_postings_fact
    LEFT JOIN
       company_dim ON job_postings_fact.company_id = company_dim.company_id    
    where  
     job_title_short = 'Data Analyst' and job_location = 'Anywhere'
    and salary_year_avg is not null 
    order by
      salary_year_avg desc
    limit 10
)
select
        top_paying_jobs.job_id,
         top_paying_jobs.job_title,
        top_paying_jobs.salary_year_avg,
        top_paying_jobs.company_name,skills
from top_paying_jobs
INNER JOIN
       skills_job_dim ON top_paying_jobs.job_id = skills_job_dim.job_id
INNER JOIN
       skills_dim ON skills_job_dim.skill_id = skills_dim.skill_id
where skills is not null 
order by
      salary_year_avg desc
      limit 10
       

